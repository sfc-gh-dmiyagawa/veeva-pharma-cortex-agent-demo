-- =====================================================================
-- 00_setup.sql : デモ専用の ROLE / WAREHOUSE / DATABASE / SCHEMA を作成
-- 実行ロール: ACCOUNTADMIN（トライアルアカウントでもそのまま実行可）
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- クロスリージョン推論（Tokyo 等で Agent の auto モデルを使うため）
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- デモ用ロール
CREATE ROLE IF NOT EXISTS VEEVA_PHARMA_DEMO_ROLE COMMENT = 'Veeva x Cortex Agent デモ管理ロール';
GRANT ROLE VEEVA_PHARMA_DEMO_ROLE TO ROLE SYSADMIN;
SET my_user = CURRENT_USER();
GRANT ROLE VEEVA_PHARMA_DEMO_ROLE TO USER IDENTIFIER($my_user);

-- デモ用ウェアハウス
CREATE WAREHOUSE IF NOT EXISTS VEEVA_PHARMA_DEMO_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Veeva x Cortex Agent デモ用';
GRANT USAGE, OPERATE ON WAREHOUSE VEEVA_PHARMA_DEMO_WH TO ROLE VEEVA_PHARMA_DEMO_ROLE;

-- デモ用データベース
CREATE DATABASE IF NOT EXISTS VEEVA_PHARMA_DEMO_DB COMMENT = 'Veeva x Cortex Agent デモ用';
GRANT OWNERSHIP ON DATABASE VEEVA_PHARMA_DEMO_DB TO ROLE VEEVA_PHARMA_DEMO_ROLE COPY CURRENT GRANTS;

-- Cortex 利用権限
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE VEEVA_PHARMA_DEMO_ROLE;

-- サービスユーザー作成・PAT 発行のための権限（09_access.sql で使用）
GRANT CREATE USER ON ACCOUNT TO ROLE VEEVA_PHARMA_DEMO_ROLE;
GRANT CREATE ROLE ON ACCOUNT TO ROLE VEEVA_PHARMA_DEMO_ROLE;

USE ROLE VEEVA_PHARMA_DEMO_ROLE;
USE WAREHOUSE VEEVA_PHARMA_DEMO_WH;
USE DATABASE VEEVA_PHARMA_DEMO_DB;

CREATE SCHEMA IF NOT EXISTS COMMERCIAL COMMENT = '製薬コマーシャル データモデル（ダミー）';
CREATE SCHEMA IF NOT EXISTS AGENTS     COMMENT = 'Semantic View / Search / Agent / MCP Server';
