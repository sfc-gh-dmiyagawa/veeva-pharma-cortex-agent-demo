-- =====================================================================
-- 07_access.sql : Veeva（MCP クライアント）接続用のロール・権限・サービスユーザー
--   01〜06 を再実行（CREATE OR REPLACE）した後は、このスクリプトも再実行して権限を付け直すこと
--   まず「すぐ繋がる」ことを優先したデモ構成（PAT = Bearer トークン）。
--   PAT 発行は 08_pat.sql、本番相当の構成は 09_oauth_optional.sql を参照。
-- 実行ロール: ACCOUNTADMIN
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- 1) MCP 実行用ロール（読み取り専用・最小権限）
CREATE ROLE IF NOT EXISTS VEEVA_PHARMA_DEMO_MCP_ROLE COMMENT = 'Veeva から MCP 経由で Agent を実行するロール';
GRANT ROLE VEEVA_PHARMA_DEMO_MCP_ROLE TO ROLE VEEVA_PHARMA_DEMO_ROLE;

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON WAREHOUSE VEEVA_PHARMA_DEMO_WH TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;

USE ROLE VEEVA_PHARMA_DEMO_ROLE;
GRANT USAGE ON DATABASE VEEVA_PHARMA_DEMO_DB TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON SCHEMA VEEVA_PHARMA_DEMO_DB.AGENTS TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON SCHEMA VEEVA_PHARMA_DEMO_DB.COMMERCIAL TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA VEEVA_PHARMA_DEMO_DB.COMMERCIAL TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT SELECT ON ALL VIEWS  IN SCHEMA VEEVA_PHARMA_DEMO_DB.COMMERCIAL TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT SELECT ON SEMANTIC VIEW VEEVA_PHARMA_DEMO_DB.AGENTS.PHARMA_COMMERCIAL_SV TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON CORTEX SEARCH SERVICE VEEVA_PHARMA_DEMO_DB.AGENTS.CALL_NOTES_SEARCH    TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON CORTEX SEARCH SERVICE VEEVA_PHARMA_DEMO_DB.AGENTS.HCP_DIRECTORY_SEARCH TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON PROCEDURE VEEVA_PHARMA_DEMO_DB.AGENTS.GET_HCP_CONTEXT(VARCHAR, VARCHAR) TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON AGENT VEEVA_PHARMA_DEMO_DB.AGENTS.PHARMA_MR_ASSISTANT TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;
GRANT USAGE ON MCP SERVER VEEVA_PHARMA_DEMO_DB.AGENTS.PHARMA_MR_MCP_SERVER TO ROLE VEEVA_PHARMA_DEMO_MCP_ROLE;

-- 2) サービスユーザー（Veeva 連携用）
USE ROLE ACCOUNTADMIN;
CREATE USER IF NOT EXISTS VEEVA_PHARMA_DEMO_MCP_USER
  TYPE = SERVICE
  DEFAULT_ROLE = VEEVA_PHARMA_DEMO_MCP_ROLE
  DEFAULT_WAREHOUSE = VEEVA_PHARMA_DEMO_WH
  COMMENT = 'Veeva CRM から Managed MCP Server を呼ぶデモ用サービスユーザー';
GRANT ROLE VEEVA_PHARMA_DEMO_MCP_ROLE TO USER VEEVA_PHARMA_DEMO_MCP_USER;

-- 3) デモ用：PAT 利用時のネットワークポリシー必須要件を緩和する認証ポリシー
--    （SERVICE ユーザーの PAT は既定でネットワークポリシーが必要。本番では Veeva の送信元 IP を
--      許可するネットワークポリシーを設定し、この緩和は外すこと）
CREATE SCHEMA IF NOT EXISTS VEEVA_PHARMA_DEMO_DB.SECURITY;
CREATE AUTHENTICATION POLICY IF NOT EXISTS VEEVA_PHARMA_DEMO_DB.SECURITY.MCP_PAT_AUTH_POLICY
  AUTHENTICATION_METHODS = ('PROGRAMMATIC_ACCESS_TOKEN', 'OAUTH')
  PAT_POLICY = (
    NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED,
    DEFAULT_EXPIRY_IN_DAYS = 30,
    MAX_EXPIRY_IN_DAYS = 90
  )
  COMMENT = 'デモ用: ネットワークポリシー無しで PAT を許可';
ALTER USER VEEVA_PHARMA_DEMO_MCP_USER UNSET AUTHENTICATION POLICY;
ALTER USER VEEVA_PHARMA_DEMO_MCP_USER SET AUTHENTICATION POLICY VEEVA_PHARMA_DEMO_DB.SECURITY.MCP_PAT_AUTH_POLICY;
