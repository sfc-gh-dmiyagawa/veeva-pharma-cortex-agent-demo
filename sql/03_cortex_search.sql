-- =====================================================================
-- 03_cortex_search.sql : Cortex Search Service
--   1) HCP_DIRECTORY_SEARCH : 医師名・カナ・施設名での医師特定（名前フォールバック用）
--   2) CALL_NOTES_SEARCH    : 面談メモの意味検索（先生の反応・懸念の把握）
-- 実行ロール: VEEVA_PHARMA_DEMO_ROLE
-- =====================================================================
USE ROLE VEEVA_PHARMA_DEMO_ROLE;
USE WAREHOUSE VEEVA_PHARMA_DEMO_WH;
USE SCHEMA VEEVA_PHARMA_DEMO_DB.AGENTS;

CREATE OR REPLACE CORTEX SEARCH SERVICE HCP_DIRECTORY_SEARCH
  ON SEARCH_TEXT
  ATTRIBUTES VEEVA_ACCOUNT_ID, HCP_ID, HCO_NAME, SPECIALTY, PREFECTURE
  WAREHOUSE = VEEVA_PHARMA_DEMO_WH
  TARGET_LAG = '1 day'
  COMMENT = '医師ディレクトリ検索（氏名・カナ・施設・診療科）'
AS
SELECT HCP_ID, VEEVA_ACCOUNT_ID, HCP_NAME, HCP_NAME_KANA, HCO_NAME, SPECIALTY, TITLE, PREFECTURE, MR_NAME,
       HCP_NAME || ' (' || HCP_NAME_KANA || ') ' || REPLACE(HCP_NAME, ' ', '') || ' / ' || HCO_NAME || ' / '
         || SPECIALTY || ' / ' || TITLE || ' / ' || PREFECTURE || ' / 担当MR: ' || MR_NAME AS SEARCH_TEXT
FROM VEEVA_PHARMA_DEMO_DB.COMMERCIAL.HCP_PROFILE_V;

CREATE OR REPLACE CORTEX SEARCH SERVICE CALL_NOTES_SEARCH
  ON CALL_NOTE
  ATTRIBUTES VEEVA_ACCOUNT_ID, HCP_ID, BRAND_NAME, HCP_REACTION, CALL_MONTH
  WAREHOUSE = VEEVA_PHARMA_DEMO_WH
  TARGET_LAG = '1 day'
  COMMENT = 'MR 面談メモの検索'
AS
SELECT c.CALL_ID, c.CALL_DATE, TO_CHAR(c.CALL_DATE, 'YYYY-MM') AS CALL_MONTH,
       p.HCP_ID, p.VEEVA_ACCOUNT_ID, p.HCP_NAME, pr.BRAND_NAME, c.CHANNEL, c.HCP_REACTION,
       c.KEY_MESSAGE, c.NEXT_ACTION, m.MR_NAME,
       c.CALL_NOTE
FROM VEEVA_PHARMA_DEMO_DB.COMMERCIAL.CALL_ACTIVITY c
JOIN VEEVA_PHARMA_DEMO_DB.COMMERCIAL.HCP p ON p.HCP_ID = c.HCP_ID
JOIN VEEVA_PHARMA_DEMO_DB.COMMERCIAL.PRODUCT pr ON pr.PRODUCT_ID = c.DETAILED_PRODUCT_ID
JOIN VEEVA_PHARMA_DEMO_DB.COMMERCIAL.MR m ON m.MR_ID = c.MR_ID;
